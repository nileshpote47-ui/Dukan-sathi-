test('reel: storyboard from saved reel script, edit, duration, picture, preview, save', async ({ page }) => {
  const errors = trackPageErrors(page)
  await login(page, users.a)

  // Without a reel script there is nothing to build from.
  await page.goto(`/dashboard/content/${ids.reelNoCopy}/storyboard`)
  await expect(page.getByText('First write the reel script with AI')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Create storyboard' })).toHaveCount(0)

  await page.goto(`/dashboard/content/${ids.reel}`)
  await page.getByRole('link', { name: 'Create reel storyboard' }).click()
  await expect(page.getByRole('heading', { name: 'Reel storyboard' })).toBeVisible()
  await page.getByRole('button', { name: 'Create storyboard' }).click()

  const scenes = page.getByRole('list', { name: 'Scenes' }).getByRole('listitem').filter({ has: page.getByRole('heading', { name: /^Scene \d+$/ }) })
  await expect(scenes.first()).toBeVisible()
  const count = await scenes.count()
  expect(count).toBeGreaterThanOrEqual(3)
  expect(count).toBeLessThanOrEqual(8)
  // Scene 1 is the saved hook; the last is the CTA.
  await expect(scenes.first().getByLabel('Text on screen')).toHaveValue('ताज़ा बासमती चावल आ गया!')
  await expect(scenes.last().getByLabel('Text on screen')).toHaveValue('आज ही आइए।')

  // Edit scene 2 text and make scene 1 longer.
  const scene2 = scenes.nth(1)
  await scene2.getByLabel('Text on screen').fill('खुशबूदार बासमती चावल')
  const scene1 = scenes.first()
  const before = await scene1.getByText(/^\d+ s$/).innerText()
  await scene1.getByRole('button', { name: 'Longer' }).click()
  await expect(scene1.getByText(/^\d+ s$/)).toHaveText(`${Number.parseInt(before) + 1} s`)

  // Assign an uploaded picture to scene 2.
  await scene2.getByText('Add a picture to this scene').click()
  await scene2.getByLabel('Upload photo').setInputFiles({ name: 'rice.png', mimeType: 'image/png', buffer: Buffer.from(mockPng(400, 300, 7)) })
  await expect(scene2.getByRole('radio', { name: 'Picture 1' })).toHaveAttribute('aria-checked', 'true', { timeout: 15_000 })
  const uploads = (await mediaRows()).filter((r) => r.source_type === 'UPLOAD')
  expect(uploads).toHaveLength(1)
  expect(uploads[0]).toMatchObject({ asset_type: 'IMAGE', status: 'READY', content_item_id: ids.reel })

  // Preview plays through the scenes.
  await expect(page.getByText(/^Scene 1 of \d+/)).toBeVisible()
  await page.getByRole('button', { name: 'Play' }).click()
  await expect(page.getByRole('button', { name: 'Pause' })).toBeVisible()
  await expect(page.getByText(/^Scene 2 of \d+/)).toBeVisible({ timeout: 15_000 })
  await page.getByRole('button', { name: 'Pause' }).click()
  await expect(page.getByText('Video file export: Coming soon')).toBeVisible()

  // Save, reload: edits, duration and picture persist.
  await page.getByRole('button', { name: 'Save storyboard' }).click()
  await expect(page.getByText('Storyboard saved.')).toBeVisible()
  await page.reload()
  await expect(scenes.nth(1).getByLabel('Text on screen')).toHaveValue('खुशबूदार बासमती चावल')
  await expect(scenes.first().getByText(/^\d+ s$/)).toHaveText(`${Number.parseInt(before) + 1} s`)
  await expect(scenes.nth(1).getByText('Picture added — change')).toBeVisible()
  await noSidewaysScroll(page)

  const { client } = await apiClientFor(users.a)
  const { data } = await client.from('content_items').select('storyboard').eq('id', ids.reel).single()
  const board = data!.storyboard as { scenes: { asset_id: string | null }[]; total_duration: number }
  expect(board.scenes[1].asset_id).toBe(uploads[0].id)
  expect(board.total_duration).toBeGreaterThanOrEqual(8)
  expect(board.total_duration).toBeLessThanOrEqual(60)

  // Content detail shows the storyboard summary; nothing was published.
  await page.goto(`/dashboard/content/${ids.reel}`)
  await expect(page.getByRole('link', { name: 'Open reel storyboard' })).toBeVisible()
  await expect(page.getByText(new RegExp(`^${count} scenes · ${board.total_duration} seconds$`))).toBeVisible()
  expect(errors).toEqual([])
})

test('safe failures: provider error is never READY, wrong files are refused', async ({ page }) => {
  await login(page, users.a)
  await page.goto(`/dashboard/content/${ids.failing}/poster`)
  const before = await mediaRows()
  await page.getByRole('button', { name: 'Create picture with AI' }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'AI content generation is temporarily unavailable' })).toBeVisible({ timeout: 15_000 })
  const failed = (await mediaRows()).filter((r) => !before.some((b) => b.id === r.id))
  expect(failed).toHaveLength(1)
  expect(failed[0]).toMatchObject({ status: 'FAILED', storage_path: null })

  // Not an image (renamed text file)
  await page.getByLabel('Upload photo').setInputFiles({ name: 'evil.png', mimeType: 'image/png', buffer: Buffer.from('<html>not an image</html>') })
  await expect(page.getByRole('alert').filter({ hasText: 'Please choose a JPG, PNG or WebP photo.' })).toBeVisible()

  // The failed item shows as Failed in the library and can be deleted.
  await page.goto(`/dashboard/media/${failed[0].id}`)
  await expect(page.getByText('This picture could not be created.')).toBeVisible()
  await expect(page.getByRole('link', { name: 'Download' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Delete' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete' }).click()
  await page.waitForURL(/\/dashboard\/media$/)
  expect((await mediaRows()).some((r) => r.id === failed[0].id)).toBe(false)
})

test('security: user B cannot see, download, change or use user A’s media', async ({ page }) => {
  const aRows = await mediaRows(users.a)
  const aPoster = aRows.find((r) => r.asset_type === 'POSTER')!
  const b = await apiClientFor(users.b)

  // API (real RLS)
  const { data: visible } = await b.client.from('media_assets').select('id').eq('id', aPoster.id)
  expect(visible).toEqual([])
  const { data: changed } = await b.client.from('media_assets').update({ metadata: {} }).eq('id', aPoster.id).select('id')
  expect(changed ?? []).toEqual([])
  const { data: removed } = await b.client.from('media_assets').delete().eq('id', aPoster.id).select('id')
  expect(removed ?? []).toEqual([])
  const { data: bBusiness } = await b.client.from('businesses').select('id').single()
  const { error: crossCreate } = await b.client.from('media_assets').insert({
    business_id: bBusiness!.id,
    content_item_id: ids.offer,
    asset_type: 'IMAGE',
    source_type: 'UPLOAD',
    status: 'GENERATING',
  })
  expect(crossCreate, 'cannot create media against A’s content').not.toBeNull()

  // Storage: private bucket, other users' files cannot be signed, listed or deleted.
  const { error: signError } = await b.client.storage.from('business-media').createSignedUrl(aPoster.storage_path!, 60)
  expect(signError).not.toBeNull()
  const { data: listed } = await b.client.storage.from('business-media').list(aPoster.storage_path!.split('/')[0])
  expect(listed ?? []).toEqual([])
  await b.client.storage.from('business-media').remove([aPoster.storage_path!])
  const publicUrl = `${process.env.NEXT_PUBLIC_SUPABASE_URL}/storage/v1/object/public/business-media/${aPoster.storage_path}`
  expect((await page.request.get(publicUrl)).status()).not.toBe(200)

  // Pages: A's media and A's poster/storyboard pages look "not found" to B.
  await login(page, users.b)
  for (const path of [`/dashboard/media/${aPoster.id}`, `/dashboard/content/${ids.offer}/poster`, `/dashboard/content/${ids.reel}/storyboard`]) {
    await page.goto(path)
    await expect(page.getByRole('heading', { name: /not found/i })).toBeVisible()
  }
  await page.goto('/dashboard/media')
  await expect(page.getByText('No media yet')).toBeVisible()

  // A's file still exists and is still A's.
  const a = await apiClientFor(users.a)
  const { data: stillThere } = await a.client.storage.from('business-media').createSignedUrl(aPoster.storage_path!, 60)
  expect(stillThere?.signedUrl).toBeTruthy()
})

test('delete: owner deletes a poster and its file', async ({ page }) => {
  const poster = (await mediaRows()).find((r) => r.asset_type === 'POSTER')!
  await login(page, users.a)
  await page.goto(`/dashboard/media/${poster.id}`)
  await page.getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByRole('dialog')).toContainText('The file is removed for good.')
  await page.getByRole('dialog').getByRole('button', { name: 'Delete' }).click()
  await page.waitForURL(/\/dashboard\/media$/)
  expect((await mediaRows()).some((r) => r.id === poster.id)).toBe(false)
  const { client, userId } = await apiClientFor(users.a)
  const { data: files } = await client.storage.from('business-media').list(userId)
  expect((files ?? []).some((f) => poster.storage_path!.endsWith(f.name))).toBe(false)
})
